package com.ppms.dayclose;

import jakarta.persistence.*;
import lombok.*;

import java.time.LocalDate;
import java.time.OffsetDateTime;

@Entity
@Table(name = "day_closes")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class DayClose {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "pump_id", nullable = false)
    private Long pumpId;

    @Column(name = "business_date", nullable = false)
    private LocalDate businessDate;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false)
    private DayCloseStatus status;

    @Column(name = "current_version", nullable = false)
    private int currentVersion;

    @Column(name = "closed_by_user_id", nullable = false)
    private Long closedByUserId;

    @Column(name = "closed_at", nullable = false)
    private OffsetDateTime closedAt;

    @Column(name = "approved_by_user_id")
    private Long approvedByUserId;

    @Column(name = "approved_at")
    private OffsetDateTime approvedAt;

    /** The DAY balance sheet generated by the latest close; null when the day had no closed shift or it was deleted. */
    @Column(name = "balance_sheet_id")
    private Long balanceSheetId;

    @Column(name = "created_at", nullable = false, updatable = false)
    private OffsetDateTime createdAt;

    @PrePersist
    protected void onCreate() {
        createdAt = OffsetDateTime.now();
    }
}
